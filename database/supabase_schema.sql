CREATE TABLE IF NOT EXISTS medicines (
 medicine_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, category varchar(50) DEFAULT 'General',
 unit_price numeric(10,2) NOT NULL CHECK(unit_price >= 0),
 stock_quantity integer NOT NULL DEFAULT 0 CHECK(stock_quantity >= 0),
 expiry_date date NOT NULL, created_at timestamptz DEFAULT now());
CREATE TABLE IF NOT EXISTS customers (
 customer_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name varchar(100) NOT NULL, phone varchar(20) NOT NULL UNIQUE,
 email varchar(100), created_at timestamptz DEFAULT now());
CREATE TABLE IF NOT EXISTS reservations (
 reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id integer NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
 reservation_date timestamptz DEFAULT now(),
 status varchar(12) NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Completed','Cancelled')),
 total_amount numeric(10,2) NOT NULL DEFAULT 0 CHECK(total_amount >= 0),
 notes varchar(255), created_at timestamptz DEFAULT now());
CREATE TABLE IF NOT EXISTS reservation_items (
 reservation_id integer NOT NULL REFERENCES reservations(reservation_id) ON DELETE CASCADE,
 medicine_id integer NOT NULL REFERENCES medicines(medicine_id) ON DELETE RESTRICT,
 quantity integer NOT NULL CHECK(quantity > 0),
 unit_price numeric(10,2) NOT NULL CHECK(unit_price >= 0),
 PRIMARY KEY (reservation_id, medicine_id));
CREATE INDEX IF NOT EXISTS idx_medicines_name ON medicines(name);
CREATE INDEX IF NOT EXISTS idx_medicines_category ON medicines(category);
CREATE INDEX IF NOT EXISTS idx_medicines_expiry ON medicines(expiry_date);
CREATE INDEX IF NOT EXISTS idx_reservations_status ON reservations(status);
CREATE INDEX IF NOT EXISTS idx_reservations_customer ON reservations(customer_id);
-- Tables are backend-only: revoke direct access from anonymous clients.
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA public FROM anon, authenticated;
